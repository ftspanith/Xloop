// ── POST /api/scrape/start — start scraping (SSE stream, auth required) ────
// Body: { mode: 1|2|3|4, channels?: number[], startDate?: string, endDate?: string }
router.post('/start', auth, (req, res) => {
  const { mode, channels, startDate, endDate } = req.body;

  // SSE headers
  res.setHeader('Content-Type',  'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection',    'keep-alive');
  res.flushHeaders();

  const send = (data) => res.write(`data: ${JSON.stringify(data)}\n\n`);

  send({ type: 'start', message: `Starting Mode ${mode} scrape...` });

  // Build args to pass to the non-interactive scrape_api.js
  const args = [
    `--mode=${mode}`,
    channels && channels.length ? `--channels=${channels.join(',')}` : '--channels=all',
  ];
  
  if (startDate) args.push(`--start-date=${startDate}`);
  if (endDate)   args.push(`--end-date=${endDate}`);

  const child = spawn('node', [SCRAPE_SCRIPT, ...args], {
    cwd: ROOT,
    env: { ...process.env },
  });

  child.stdout.on('data', (data) => {
    const lines = data.toString().split('\n').filter(l => l.trim());
    lines.forEach(line => send({ type: 'log', message: line }));
  });

  child.stderr.on('data', (data) => {
    const lines = data.toString().split('\n').filter(l => l.trim());
    lines.forEach(line => send({ type: 'error', message: line }));
  });

  child.on('close', (code) => {
    let fileSize = '';
    try {
      if (fs.existsSync(EXPORT_FILE)) {
        const mb = (fs.statSync(EXPORT_FILE).size / 1024 / 1024).toFixed(2);
        fileSize = `${mb} MB`;
      }
    } catch(_) {}

    send({
      type:     code === 0 ? 'done' : 'fail',
      message:  code === 0 ? ' Scrape complete! telegram_export.json is ready.' : ` Scraper exited with code ${code}`,
      fileSize,
    });
    res.end();
  });

  req.on('close', () => child.kill());
});

// ── POST /api/scrape/upload-export — upload telegram_export.json from local PC ──
// On Vercel, scrape_api.js cannot run. Instead, user uploads the JSON file
// generated by the local Telegram scraper. We store it in MongoDB (not /tmp)
// so it persists across Lambda invocations.
router.post('/upload-export', auth, express.json({ limit: '200mb' }), async (req, res) => {
  try {
    const PipelineCache = require('../models/PipelineCache');
    const { parseMessageBlock, classifyUrl, isJunkTitle } = require('../utils/parser');
    const data = req.body;

    // Support single OR multiple export files:
    //   Single: { messages: [...] }  OR  [...]
    //   Multi:  [ { messages: [...] }, { messages: [...] }, ... ]
    let allMessages;
    if (Array.isArray(data)) {
      // Could be array of messages OR array of export objects
      if (data.length > 0 && data[0] && typeof data[0] === 'object' && Array.isArray(data[0].messages)) {
        // Array of exports → merge all
        allMessages = data.flatMap(d => d.messages || []);
      } else {
        // Raw array of messages
        allMessages = data;
      }
    } else if (data.messages && Array.isArray(data.messages)) {
      allMessages = data.messages;
    } else {
      return res.status(400).json({ message: 'Invalid format. Expected { messages:[...] }, an array of messages, or an array of exports.' });
    }

    // Global dedup by channel_id:message_id (handles overlapping files)
    const msgMap = new Map();
    for (const m of allMessages) {
      const key = `${m.channel_id || '0'}:${m.id}`;
      if (!msgMap.has(key)) msgMap.set(key, m);
    }
    const messages = [...msgMap.values()];
    const rawCount = allMessages.length;
    const dedupCount = rawCount - messages.length;

    // ── Run extraction inline (same logic as extract_links.js) ───────────────
    // We extract here instead of storing raw JSON (raw JSON = 50MB+ > MongoDB 16MB limit)
    const HOST_PRIORITY = ['GDFlix','HubCloud','FilePress','DTFlix','TMBCloud','Direct','Download'];
    const MAX_HOSTS = 3;
    const hostRank = h => { const i = HOST_PRIORITY.indexOf(h); return i === -1 ? 99 : i; };
    const CDN_RE = [/\.(m3u8|ts|m4s)(\?|$)/i, /\/(image|img|thumbnail|poster|banner|cover)\//i,
      /\/(uploads?|wp-content|static|assets?)\//i, /cdn\.(hotstar|zee5|sonyliv)/i,
      /vod\d*\./i, /img\d*\./i, /thumbs?\./i, /akamaized\.net/i, /cloudfront\.net/i];
    const isJunkUrl = u => { if (!u) return true;
      if (/workers\.dev/i.test(u)) return !/\.(mkv|mp4|avi|zip|rar)([?#]|$)/i.test(u);
      return CDN_RE.some(r => r.test(u)); };
    const slotKey = e => {
      const sz = (e.size||'').replace(/\s/g,'').toLowerCase();
      const fn = (e.filename||'').toLowerCase().trim().slice(0,80);
      let d = '';
      if (!sz && !fn) { try { d = new URL(e.url).hostname.replace('www.',''); } catch { d = e.url.slice(0,40); } }
      return `${(e.quality||'HD').toLowerCase()}|${sz}|${fn}|${(e.language||'').toLowerCase()}|${e.season??''}|${e.episode??''}|${d}`;
    };

    const extracted = []; const shortlinks = [];
    const seenUrls = new Set();
    let skipped = 0;

    for (const msg of messages) {
      let rawText = '';
      if (typeof msg.text === 'string') rawText = msg.text;
      else if (Array.isArray(msg.text)) rawText = msg.text.map(p => {
        if (typeof p === 'string') return p;
        if (p.type === 'text_link' && p.href) return `${p.text}\n${p.href}\n`;
        return p.text || '';
      }).join('');
      if (msg.reply_markup?.inline_keyboard) {
        for (const row of msg.reply_markup.inline_keyboard)
          for (const btn of (row||[])) if (btn.url) rawText += `\n${btn.url}`;
      }
      if (!rawText.trim()) { skipped++; continue; }
      const parsed = parseMessageBlock(rawText, msg.id);
      if (!parsed || !parsed.downloads?.length || !parsed.title || isJunkTitle(parsed.title)) { skipped++; continue; }

      const msgSlots = new Map();
      for (const dl of parsed.downloads) {
        const lang = dl.language || parsed.language || '';
        if (!dl.size && !dl.filename && !lang && dl.season === null && !parsed.title) continue;
        for (const link of dl.links) {
          const url = link.url.replace(/^http:\/\//i,'https://').replace(/\/$/,'');
          if (isJunkUrl(url) || seenUrls.has(url)) continue;
          const urlType = classifyUrl(url);
          if (urlType === 'Ignore' || urlType === 'Paste') continue;
          const entry = { messageId: parsed.messageId, title: parsed.title, year: parsed.year,
            contentType: parsed.contentType, isSeries: parsed.isSeries,
            season: dl.season??parsed.season, episode: dl.episode??parsed.episode,
            language: lang, quality: dl.quality, size: dl.size, filename: dl.filename,
            host: urlType, url, bypassedUrl: null,
            isFast: /gdflix|hubcloud|gdlink|tmbcloud|fpgo|filebee/i.test(url),
            imdbId: parsed.imdbId||null, tmdbIdHint: parsed.tmdbIdHint||null };
          if (urlType === 'Shortlink') { shortlinks.push(entry); seenUrls.add(url); continue; }
          const sk = slotKey(entry);
          if (msgSlots.has(sk)) {
            const sl = msgSlots.get(sk);
            if (!sl.some(e=>e.host===urlType) && sl.length < MAX_HOSTS) sl.push(entry);
          } else { msgSlots.set(sk, [entry]); }
        }
      }
      for (const sl of msgSlots.values()) {
        sl.sort((a,b)=>hostRank(a.host)-hostRank(b.host));
        for (const e of sl) { seenUrls.add(e.url); extracted.push(e); }
      }
    }

    // Merge shortlinks in
    const allLinks = [...extracted, ...shortlinks];

    // ── Save to ExtractedLink collection (one doc per link — no 16MB limit) ──
    // Each upload gets a batch ID so we can atomically replace the previous batch.
    const ExtractedLink = require('../models/ExtractedLink');
    const batchId = `batch_${Date.now()}`;

    // Tag all entries with this batch ID
    allLinks.forEach(e => { e.uploadBatch = batchId; });

    // Insert new batch in chunks of 500
    const CHUNK = 500;
    for (let i = 0; i < allLinks.length; i += CHUNK) {
      await ExtractedLink.insertMany(allLinks.slice(i, i + CHUNK), { ordered: false });
    }

    // Delete all previous batches (keep only the new one)
    await ExtractedLink.deleteMany({ uploadBatch: { $ne: batchId } });

    // Save a small metadata record in PipelineCache (just count + batchId, no data)
    await PipelineCache.findOneAndUpdate(
      { key: 'extracted_links' },
      { key: 'extracted_links', data: { batchId, count: allLinks.length }, count: allLinks.length, savedAt: new Date() },
      { upsert: true, new: true }
    );

    // Write links_for_bypasser.json to /tmp for immediate same-Lambda pipeline use
    try {
      fs.writeFileSync(path.join(os.tmpdir(), 'links_for_bypasser.json'), JSON.stringify(allLinks));
      fs.writeFileSync(path.join(os.tmpdir(), 'shortlinks_report.json'), JSON.stringify(shortlinks));
    } catch(_) {}

    const dedupNote = dedupCount > 0 ? ` (${dedupCount} duplicate messages removed across files)` : '';
    res.json({
      message: `✅ Extracted ${allLinks.length} links from ${messages.length} messages (${skipped} skipped)${dedupNote}. Saved to MongoDB. Run Full Pipeline now.`,
      count: allLinks.length, messages: messages.length, rawMessages: rawCount, duplicatesRemoved: dedupCount, skipped,
    });
  } catch (err) {
    res.status(500).json({ message: `Upload failed: ${err.message}` });
  }
});

// ── GET /api/scrape/export-status — check if extracted links are available ────
router.get('/export-status', auth, async (req, res) => {
  try {
    const PipelineCache = require('../models/PipelineCache');
    const cache = await PipelineCache.findOne({ key: 'extracted_links' }, 'count savedAt').lean();
    const tmpExists = fs.existsSync(path.join(os.tmpdir(), 'links_for_bypasser.json'));
    res.json({
      available: !!(cache || tmpExists),
      source: cache ? 'mongodb' : tmpExists ? 'tmp' : 'none',
      count: cache ? cache.count : 0,
      savedAt: cache ? cache.savedAt : null,
    });
  } catch (err) {
    res.json({ available: false, source: 'error', error: err.message });
  }
});

