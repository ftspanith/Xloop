// ── POST /api/scrape/start — start scraping (SSE stream, auth required) ────
// Body: { mode: 1|2|3|4, channels?: number[], startDate?: string, endDate?: string }
router.post('/start', auth, (req, res) => {
  const { mode, channels, startDate, endDate } = req.body;

  // SSE headers
  res.setHeader('Content-Type',  'text/event-stream');
  res.setHeader('Cache-Control', 'no-cache');
  res.setHeader('Connection',    'keep-alive');
  res.flushHeaders();

  const send = (data) => res.write(`data: ${JSON.stringify(data)}\n\n`);

  send({ type: 'start', message: `Starting Mode ${mode} scrape...` });

  // Build args to pass to the non-interactive scrape_api.js
  const args = [
    `--mode=${mode}`,
    channels && channels.length ? `--channels=${channels.join(',')}` : '--channels=all',
  ];
  
  if (startDate) args.push(`--start-date=${startDate}`);
  if (endDate)   args.push(`--end-date=${endDate}`);

  const child = spawn('node', [SCRAPE_SCRIPT, ...args], {
    cwd: ROOT,
    env: { ...process.env },
  });

  child.stdout.on('data', (data) => {
    const lines = data.toString().split('\n').filter(l => l.trim());
    lines.forEach(line => send({ type: 'log', message: line }));
  });

  child.stderr.on('data', (data) => {
    const lines = data.toString().split('\n').filter(l => l.trim());
    lines.forEach(line => send({ type: 'error', message: line }));
  });

  child.on('close', (code) => {
    let fileSize = '';
    try {
      if (fs.existsSync(EXPORT_FILE)) {
        const mb = (fs.statSync(EXPORT_FILE).size / 1024 / 1024).toFixed(2);
        fileSize = `${mb} MB`;
      }
    } catch(_) {}

    send({
      type:     code === 0 ? 'done' : 'fail',
      message:  code === 0 ? ' Scrape complete! telegram_export.json is ready.' : ` Scraper exited with code ${code}`,
      fileSize,
    });
    res.end();
  });

  req.on('close', () => child.kill());
});

// ── POST /api/scrape/upload-export — upload telegram_export.json from local PC ──
// On Vercel, scrape_api.js cannot run. Instead, user uploads the JSON file
// generated by the local Telegram scraper. We store it in MongoDB (not /tmp)
// so it persists across Lambda invocations.
router.post('/upload-export', auth, express.json({ limit: '200mb' }), async (req, res) => {
  try {
    const PipelineCache = require('../models/PipelineCache');
    const data = req.body;

    if (!data || (!Array.isArray(data.messages) && !Array.isArray(data))) {
      return res.status(400).json({ message: 'Invalid telegram_export.json format. Expected { messages: [...] } or an array.' });
    }

    const messages = Array.isArray(data) ? data : data.messages;
    const count = messages.length;

    // Save raw export to MongoDB cache
    await PipelineCache.findOneAndUpdate(
      { key: 'telegram_export' },
      { key: 'telegram_export', data, count, savedAt: new Date() },
      { upsert: true, new: true }
    );

    // Also write to /tmp for immediate use in same Lambda invocation
    try {
      fs.writeFileSync(path.join(os.tmpdir(), 'telegram_export.json'), JSON.stringify(data));
    } catch(_) {}

    res.json({ message: `✅ telegram_export.json uploaded — ${count} messages saved to MongoDB. Run Full Pipeline now.`, count });
  } catch (err) {
    res.status(500).json({ message: `Upload failed: ${err.message}` });
  }
});

// ── GET /api/scrape/export-status — check if telegram_export is available ─────
router.get('/export-status', auth, async (req, res) => {
  try {
    const PipelineCache = require('../models/PipelineCache');
    const cache = await PipelineCache.findOne({ key: 'telegram_export' }, 'count savedAt').lean();
    const tmpExists = fs.existsSync(path.join(os.tmpdir(), 'telegram_export.json'));
    res.json({
      available: !!(cache || tmpExists),
      source: cache ? 'mongodb' : tmpExists ? 'tmp' : 'none',
      count: cache ? cache.count : 0,
      savedAt: cache ? cache.savedAt : null,
    });
  } catch (err) {
    res.json({ available: false, source: 'error', error: err.message });
  }
});

module.exports = router;
